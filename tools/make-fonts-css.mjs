// One-time helper (already run – the result, css/fonts.css, is included, so nobody needs to run this;
// it only works next to the original "v2" folder that holds the font files).
// Embeds the Quicksand font (SIL Open Font Licence) as base64 so the
// site shows Vietnamese text correctly offline, with nothing to load from disk.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const fontDir = join(here, '..', '..', 'v2', 'bio-explorer-lab', '.vinext', 'fonts', 'quicksand-10c57033d397');

const subsets = [
  ['vietnamese', 'quicksand-8c18ec0b.woff2',
    'U+0102-0103, U+0110-0111, U+0128-0129, U+0168-0169, U+01A0-01A1, U+01AF-01B0, U+0300-0301, U+0303-0304, U+0308-0309, U+0323, U+0329, U+1EA0-1EF9, U+20AB'],
  ['latin-ext', 'quicksand-db92d280.woff2',
    'U+0100-02BA, U+02BD-02C5, U+02C7-02CC, U+02CE-02D7, U+02DD-02FF, U+0304, U+0308, U+0329, U+1D00-1DBF, U+1E00-1E9F, U+1EF2-1EFF, U+2020, U+20A0-20AB, U+20AD-20C0, U+2113, U+2C60-2C7F, U+A720-A7FF'],
  ['latin', 'quicksand-422bee69.woff2',
    'U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD'],
];

let css = '/* Quicksand (SIL Open Font Licence) - embedded so the site works offline. Generated by tools/make-fonts-css.mjs */\n';
for (const [name, file, range] of subsets) {
  const b64 = readFileSync(join(fontDir, file)).toString('base64');
  css += `/* ${name} */\n@font-face {\n  font-family: 'Quicksand';\n  font-style: normal;\n  font-weight: 300 700;\n  font-display: swap;\n` +
    `  src: url(data:font/woff2;base64,${b64}) format('woff2');\n  unicode-range: ${range};\n}\n`;
}
writeFileSync(join(here, '..', 'css', 'fonts.css'), css);
console.log('fonts.css written:', (css.length / 1024).toFixed(0), 'KB');
